import {reportHtml} from '../../packages/report-renderer/src/template.js';
import { signIn } from './auth.js';
import { expect, test } from '@playwright/test';
test.use({actionTimeout: 5000});

test('opens projects by keyboard, preserves context and runs the prepared virtual demo', async ({ page }) => {
  test.setTimeout(90000);
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await signIn(page);
  await page.getByRole('button', {name:'Projects',exact:true}).click();
  await page.getByRole('button', {name:'Open demo project',exact:true}).click();
  await expect(page.getByRole('heading', {name:'Automation demo',exact:true})).toBeVisible();
  await expect(page).toHaveURL(/project=[0-9a-f-]+/);
  const projectUrl = page.url();
  await page.reload();
  await expect(page.getByRole('heading', {name:'Automation demo',exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Devices',exact:true}).click();
  await expect(page.getByRole('article')).toHaveCount(2);
  const thermal = page.getByRole('article').filter({hasText:'Climate chamber'});
  await thermal.getByRole('button', {name:'Start simulator',exact:true}).click();
  await expect(thermal.getByText('Simulation running',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Signals',exact:true}).click();
  const numericRow=page.getByRole('row').filter({hasText:'Chamber temperature (C)'});
  await numericRow.getByText('Display settings',{exact:true}).click();
  await numericRow.getByLabel('Unit for Chamber temperature (C)',{exact:true}).fill('°C');
  await numericRow.getByLabel('Decimal places for Chamber temperature (C)',{exact:true}).fill('1');
  await numericRow.getByRole('button',{name:'Save display settings',exact:true}).click();
  await expect(numericRow.locator('.signal-value')).toHaveText(/^-?\d+\.\d °C$/);
  await page.reload();
  await expect(numericRow.locator('.signal-value')).toHaveText(/^-?\d+\.\d °C$/);

  await page.getByRole('button', {name:'Logic',exact:true}).click();
  await page.getByRole('button', {name:'Open Climate PID',exact:true}).click();
  await expect(page.getByText('Prepared revisions',{exact:true})).toBeVisible();
  await page.getByLabel('Activation reason',{exact:true}).fill('Demo acceptance');
  await page.getByRole('button', {name:'Activate revision 1',exact:true}).click();
  await expect(page.getByRole('status',{name:'Graph runtime'})).toContainText('running');
  await page.getByRole('button', {name:'Screens',exact:true}).click();
  await page.getByRole('button', {name:'Open Climate overview',exact:true}).click();
  await page.getByRole('button', {name:'Operate revision 1',exact:true}).click();
  await expect(page.getByRole('region', {name:'Live numeric values'})).toContainText('Good');
  await expect(page.getByRole('region',{name:'Live numeric values'})).toContainText(/\d+\.\d °C/);
  const temperatureTrend=page.getByRole('region',{name:'Trend Temperature history',exact:true});
  await expect(temperatureTrend.getByText('Unit: °C',{exact:true})).toBeVisible();
  await temperatureTrend.getByRole('button',{name:'Inspect history',exact:true}).click();
  await expect(page.getByRole('table',{name:'Signal history',exact:true})).toContainText('°C');
  const rawDownload=page.waitForEvent('download');await page.getByRole('button',{name:'Export loaded CSV',exact:true}).click();
  const rawChunks:Buffer[]=[];for await(const chunk of await (await rawDownload).createReadStream())rawChunks.push(Buffer.from(chunk));
  const rawCsv=Buffer.concat(rawChunks).toString();expect(rawCsv).toContain('export_version,unit,display_decimals,signal_revision');expect(rawCsv).toContain('"2","°C","1"');
  await page.getByRole('button',{name:'Show reports',exact:true}).click();
  await page.getByLabel('Report date (UTC)',{exact:true}).fill('2026-10-12');
  await page.getByRole('button',{name:'Generate report',exact:true}).click();
  const job=page.getByRole('table',{name:'Report jobs',exact:true}).getByRole('row').filter({hasText:'2026-10-12'});
  await expect(job).toContainText('Ready',{timeout:15000});
  await job.getByRole('button',{name:'View report',exact:true}).click();
  await expect(page.getByRole('region',{name:'Report preview',exact:true})).toContainText('Unit: °C · 1 decimal places');
  const href=await job.getByRole('link',{name:'Download PDF',exact:true}).getAttribute('href');
  const saved=await (await page.request.get(href!.replace(/\/pdf$/,''))).json();
  expect(saved.report).toMatchObject({templateVersion:2,signal:{unit:'°C',displayDecimals:1}});
  expect((await (await page.request.get(href!)).body()).subarray(0,5).toString()).toBe('%PDF-');
  const csv=await (await page.request.get(href!.replace(/\/pdf$/,'/csv'))).text();
  expect(csv).toContain('unit,display_decimals,signal_revision');expect(csv).toContain('"°C","1"');
  const print=await page.context().newPage();await print.setViewportSize({width:1123,height:794});await print.emulateMedia({media:'print'});
  await print.setContent(reportHtml(saved.report));await expect(print.getByText(/Units: °C/)).toBeVisible();
  await print.screenshot({path:'test-results/report-units-print.png',fullPage:true});await print.close();

  await page.getByRole('button',{name:'Close history',exact:true}).click();
  await page.getByRole('button',{name:'Back to editor',exact:true}).click();
  const metadataPath=/\/api\/v1\/signals\/[0-9a-f-]{36}$/;
  await page.route(metadataPath,route=>route.fulfill({status:503,json:{message:'Metadata fixture outage'}}));
  await page.getByRole('button',{name:'Operate revision 1',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('display settings are unavailable');
  await expect(page.getByRole('region',{name:'Live numeric values'}).locator('strong')).not.toContainText('°C');
  await page.unroute(metadataPath);
  await page.getByRole('button',{name:'Retry display settings',exact:true}).click();
  await expect(page.getByRole('region',{name:'Live numeric values'})).toContainText(/\d+\.\d °C/);
  await expect(page.getByRole('button',{name:'Retry display settings',exact:true})).toHaveCount(0);
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('region',{name:'Trend Temperature history',exact:true}).getByText('Unit: °C',{exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/presentation-units-phone.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});


  await page.getByRole('button', {name:'Logic',exact:true}).click();
  await page.getByRole('button', {name:'Open Climate PID',exact:true}).click();
  await page.getByLabel('Activation reason',{exact:true}).fill('End demo acceptance');
  await page.getByRole('button', {name:'Stop graph',exact:true}).click();
  await page.getByRole('button', {name:'Devices',exact:true}).click();
  await expect(thermal.getByText('Simulation stopped',{exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Projects',exact:true}).click();
  const link = page.getByRole('link', {name:/Open Automation demo/});
  await link.focus(); await page.keyboard.press('Enter');
  await expect(page).toHaveURL(projectUrl);
  await page.goBack(); await expect(page.getByRole('heading',{name:'Your projects',exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});

test('edits catalog names, filters a project and preserves metadata after reload', async ({page}) => {
  await signIn(page);
  await page.getByRole('button',{name:'Projects',exact:true}).click();
  await page.getByLabel('Project name',{exact:true}).fill('Catalog metadata bench');
  await page.getByRole('button',{name:'Create project',exact:true}).click();
  await page.getByRole('link',{name:'Open Catalog metadata bench',exact:true}).click();
  await page.getByRole('button',{name:'Open devices',exact:true}).click();
  await page.getByLabel('Device name',{exact:true}).fill('Test lamp');
  await page.getByLabel('Site ID',{exact:true}).fill('catalog-browser');
  await page.getByLabel('Device address',{exact:true}).fill('lamp');
  await page.getByRole('button',{name:'Add device',exact:true}).click();
  const card=page.getByRole('article'); await expect(card).toHaveCount(1);
  await card.locator('summary').click();
  await card.getByLabel('New name for Test lamp',{exact:true}).fill('Workshop light');
  await card.getByRole('button',{name:'Save name',exact:true}).click();
  await expect(card.getByRole('heading',{name:'Workshop light',exact:true})).toBeVisible();
  await page.getByLabel('Search devices',{exact:true}).fill('unmatched'); await expect(card).toHaveCount(0);
  await page.getByLabel('Search devices',{exact:true}).fill('Workshop'); await expect(card).toHaveCount(1);
  await page.getByRole('button',{name:'Signals',exact:true}).click();
  const row=page.getByRole('row').filter({hasText:'Test lamp.led'});
  await row.locator('summary').click();
  await row.getByLabel('New name for Test lamp.led',{exact:true}).fill('Workshop output');
  await row.getByRole('button',{name:'Save name',exact:true}).click();
  await expect(page.getByRole('row').filter({hasText:'Workshop output'})).toBeVisible();
  await page.reload(); await expect(page.getByRole('row').filter({hasText:'Workshop output'})).toBeVisible();
  await page.getByRole('button',{name:'Project home',exact:true}).click();
  await page.locator('summary').click();
  await page.getByLabel('New name for Catalog metadata bench',{exact:true}).fill('Workshop project');
  await page.getByRole('button',{name:'Save name',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Workshop project',exact:true})).toBeVisible();
});
