import {expect,test} from '@playwright/test';
import {signIn} from './auth.js';
test('publishes thermal recipes, preserves frozen runs and completes headlessly with fault injection',async({page})=>{
 test.setTimeout(90000);
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await signIn(page);
 await page.getByRole('button',{name:'Projects',exact:true}).click();
 await page.getByLabel('Project name',{exact:true}).fill('Recipe acceptance');
 await page.getByRole('button',{name:'Create project',exact:true}).click();
 await page.getByRole('button',{name:'Recipes',exact:true}).click();
 await page.getByLabel('Recipe project',{exact:true}).selectOption({label:'Recipe acceptance'});
 await page.getByLabel('Target temperature (C)',{exact:true}).fill('21');
 await page.getByLabel('Hold duration (seconds)',{exact:true}).fill('1');
 await page.getByRole('button',{name:'Publish recipe version',exact:true}).click();
 await page.getByRole('button',{name:'Start simulation v1',exact:true}).click();
 await expect(page.getByTestId('recipe-status').first()).toHaveText('Running');
 await page.getByLabel('Target temperature (C)',{exact:true}).fill('30');
 await page.getByRole('button',{name:'Publish recipe version',exact:true}).click();
 await expect(page.getByRole('button',{name:'Start simulation v2',exact:true})).toBeVisible();
 await expect(page.locator('.recipe-run').first()).toContainText('Frozen parameters: 21 C');
 // Leave the page completely: the server must continue without read requests.
 const url=page.url();await page.goto('about:blank');await page.waitForTimeout(4000);await page.goto(url);
 await expect(page.getByTestId('recipe-status').first()).toHaveText('Completed');
 await expect(page.locator('.recipe-run').first()).toContainText('Heater OFF');
 await page.getByRole('button',{name:'Start simulation v2',exact:true}).click();
 await page.getByRole('button',{name:'Simulate permit loss',exact:true}).click();
 await expect(page.getByTestId('recipe-status').first()).toHaveText('Aborted');
 await expect(page.locator('.recipe-run').first()).toContainText('Simulation permit lost');
 await page.getByRole('button',{name:'Start simulation v2',exact:true}).click();
 await page.getByRole('button',{name:'Simulate bad quality',exact:true}).click();
 await expect(page.locator('.recipe-run').first()).toContainText('Simulation signal quality is not Good');
 await page.getByRole('button',{name:'Start simulation v2',exact:true}).click();
 await page.getByRole('button',{name:'Cancel simulation',exact:true}).click();
 await expect(page.locator('.recipe-run').first()).toContainText('Cancelled by operator');
 await page.locator('.recipe-run').first().getByText('Run events (2)',{exact:true}).click();
 await page.screenshot({path:'test-results/recipes-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/recipes-mobile.png',fullPage:true});
 expect(errors).toEqual([]);
});

test('edits ordered steps and executes a frozen heat-hold-cool program',async({page})=>{
 test.setTimeout(90000);const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await signIn(page);
 await page.getByRole('button',{name:'Projects',exact:true}).click();
 await page.getByLabel('Project name',{exact:true}).fill('Multi-step recipes');
 await page.getByRole('button',{name:'Create project',exact:true}).click();
 await page.getByRole('button',{name:'Recipes',exact:true}).click();
 await page.getByLabel('Recipe project',{exact:true}).selectOption({label:'Multi-step recipes'});
 await page.getByRole('button',{name:'New multi-step demo',exact:true}).click();
 await page.getByLabel('Step 1 name',{exact:true}).fill('Warm batch');
 await page.getByLabel('Step 1 target',{exact:true}).fill('21');
 await page.getByLabel('Step 2 target',{exact:true}).fill('21');
 await page.getByLabel('Step 2 seconds',{exact:true}).fill('1');
 await page.getByLabel('Step 3 target',{exact:true}).fill('20.9');
 await page.getByRole('button',{name:'Add step',exact:true}).click();
 await expect(page.getByLabel('Step 4 action',{exact:true})).toHaveValue('hold');
 await page.getByRole('button',{name:'Remove step 4',exact:true}).click();
 await page.getByRole('button',{name:'Move step 3 up',exact:true}).click();
 await expect(page.getByLabel('Step 2 action',{exact:true})).toHaveValue('cool');
 await page.getByRole('button',{name:'Move step 2 down',exact:true}).click();
 await expect(page.getByLabel('Step 3 action',{exact:true})).toHaveValue('cool');
 await page.getByRole('button',{name:'Publish recipe version',exact:true}).click();
 await expect(page.locator('.recipe-version').first()).toContainText('3 steps · Heat → Hold → Cool');
 await page.locator('.recipe-version').first().getByText('View parameters',{exact:true}).click();
 await expect(page.locator('.recipe-version').first().getByText('Warm batch',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Start simulation v1',exact:true}).click();
 await expect(page.getByTestId('recipe-status').first()).toHaveText('Running');
 await page.getByLabel('Step 1 name',{exact:true}).fill('Next batch');
 await page.getByRole('button',{name:'Publish recipe version',exact:true}).click();
 await expect(page.getByRole('button',{name:'Start simulation v2',exact:true})).toBeVisible();
 await expect(page.locator('.recipe-run').first()).toContainText('Warm batch');
 await expect(page.locator('.recipe-run').first()).not.toContainText('Next batch');
 const url=page.url();await page.goto('about:blank');await page.waitForTimeout(8000);await page.goto(url);
 await expect(page.getByTestId('recipe-status').first()).toHaveText('Completed',{timeout:10000});
 await expect(page.locator('.recipe-run').first()).toContainText('Heater OFF');
 await page.locator('.recipe-run').first().getByText('Run events (4)',{exact:true}).click();
 await expect(page.locator('.recipe-run').first()).toContainText('Step 2: Hold temperature (Holding)');
 await expect(page.locator('.recipe-run').first()).toContainText('Step 3: Cool chamber (Cooling)');
 await page.getByRole('button',{name:'Edit from v2',exact:true}).click();
 await expect(page.getByLabel('Step 1 name',{exact:true})).toHaveValue('Next batch');
 await page.screenshot({path:'test-results/recipe-steps-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/recipe-steps-mobile.png',fullPage:true});
 expect(errors).toEqual([]);
});
