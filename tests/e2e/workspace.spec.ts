import { expect, test, type Page } from '@playwright/test';

async function login(page: Page) {
  await page.goto('/');
  await page.getByLabel('Username', { exact: true }).fill('operator');
  await page.getByLabel('Password', { exact: true }).fill('E2E fixture password only!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Overview', exact: true })).toBeVisible();
}

test('creates a project and virtual device, verifies a command, and audits the workflow', async ({ page }) => {
  test.setTimeout(60000);
  const errors: string[] = [];
  const external: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('request', (request) => { if (new URL(request.url()).hostname !== 'localhost') external.push(request.url()); });
  await login(page);
  await page.getByRole('button', { name: 'Projects', exact: true }).click();
  await page.getByLabel('Project name', { exact: true }).fill('Browser LED Demo');
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  await expect(page.getByText('Browser LED Demo', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Devices', exact: true }).click();
  await page.getByLabel('Device name', { exact: true }).fill('Workbench LED');
  await page.getByLabel('Site ID', { exact: true }).fill('demo');
  await page.getByLabel('Device address', { exact: true }).fill('esp32-1');
  await page.getByRole('button', { name: 'Add device', exact: true }).click();
  await expect(page.getByText('Workbench LED', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Signals', exact: true }).click();
  await expect(page.getByText('Workbench LED.led', { exact: true })).toBeVisible();
  await expect(page.getByRole('row').filter({ hasText: 'Workbench LED.led' })).toContainText('Disconnected');
  await expect(page.getByRole('row').filter({ hasText: 'Workbench LED.led' })).toContainText('No data');
  await page.getByRole('button', { name: 'Devices', exact: true }).click();
  const card = page.getByRole('article').filter({ hasText: 'Workbench LED' });
  await card.getByRole('button', { name: 'Start simulator', exact: true }).click();
  await expect(card.getByText('Simulation running', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Signals', exact: true }).click();
  const row = page.getByRole('row').filter({ hasText: 'Workbench LED.led' });
  await expect(row).toContainText('Good');
  await row.getByRole('button', { name: 'Control', exact: true }).click();
  await page.getByLabel('Command reason', { exact: true }).fill('Browser LED commissioning');
  await page.getByRole('button', { name: 'Send ON', exact: true }).click();
  await expect(page.getByRole('status', { name: 'Command status' })).toContainText('Verified');
  await expect(row).toContainText('ON');
  await page.screenshot({ path: 'test-results/manual-control.png', fullPage: true });
  await page.getByRole('button', { name: 'Devices', exact: true }).click();
  await card.getByRole('button', { name: 'Stop simulator', exact: true }).click();
  await expect(card.getByText('Simulation stopped', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Signals', exact: true }).click();
  await row.getByRole('button', { name: 'History', exact: true }).click();
  const history = page.getByRole('table', { name: 'Signal history' });
  await expect(history).toContainText('ON');
  await expect(history).toContainText('Disconnected');
  await expect(page.getByRole('img', { name: 'Signal history trend' })).toBeVisible();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export loaded CSV', exact: true }).click();
  const file = await downloaded; expect(file.suggestedFilename()).toMatch(/^open-apcs-history-.*\.csv$/);
  const stream = await file.createReadStream(); const chunks: Buffer[] = [];
  for await (const chunk of stream) chunks.push(Buffer.from(chunk));
  const csv = Buffer.concat(chunks).toString('utf8');
  expect(csv).toContain('observed_at_utc,value_json,quality'); expect(csv).toContain('"Disconnected"'); expect(csv).toContain('"true"');
  await page.screenshot({ path: 'test-results/signal-history.png', fullPage: true });
  await page.setViewportSize({ width: 360, height: 800 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect.poll(() => page.locator('.sidebar').evaluate((element) => element.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await page.screenshot({ path: 'test-results/signal-history-phone.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Alarms', exact: true }).click();
  await page.getByLabel('Alarm name', { exact: true }).fill('LED offline');
  await page.getByLabel('Alarm signal', { exact: true }).selectOption({ label: 'Workbench LED.led' });
  await page.getByLabel('Alarm condition', { exact: true }).selectOption('unavailable');
  await page.getByRole('button', { name: 'Create alarm', exact: true }).click();
  const alarm = page.getByRole('row').filter({ hasText: 'LED offline' });
  await expect(alarm).toContainText('ActiveUnacknowledged');
  await alarm.getByRole('button', { name: 'Inspect', exact: true }).click();
  await page.getByLabel('Alarm action reason', { exact: true }).fill('Inspected disconnected simulator');
  await page.getByRole('button', { name: 'Acknowledge', exact: true }).click();
  await expect(alarm).toContainText('ActiveAcknowledged');
  await page.getByRole('button', { name: 'Suppress for one minute', exact: true }).click();
  await expect(alarm).toContainText('Suppressed');
  await page.getByRole('button', { name: 'Remove suppression', exact: true }).click();
  await expect(alarm).not.toContainText('Suppressed');
  await page.screenshot({ path: 'test-results/alarms.png', fullPage: true });
  await page.getByRole('button', { name: 'Devices', exact: true }).click();
  await card.getByRole('button', { name: 'Start simulator', exact: true }).click();
  await expect(card.getByText('Simulation running', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Alarms', exact: true }).click();
  await expect(alarm).toContainText('Normal');
  await alarm.getByRole('button', { name: 'Inspect', exact: true }).click();
  await expect(page.getByRole('table', { name: 'Alarm events' })).toContainText('Returned');

  await page.getByRole('button', { name: 'Devices', exact: true }).click();
  await page.getByLabel('Device name', { exact: true }).fill('TLS LED bench');
  await page.getByRole('combobox', { name: 'Device profile', exact: true }).selectOption('esp32-led');
  await page.getByLabel('Site ID', { exact: true }).fill('tls-e2e');
  await page.getByLabel('Device address', { exact: true }).fill('led');
  await page.getByRole('button', { name: 'Add device', exact: true }).click();
  const bench = page.getByRole('article').filter({ hasText: 'TLS LED bench' });
  await expect(bench.getByRole('button', { name: 'Arm LED bench', exact: true })).toBeDisabled();
  await bench.getByRole('combobox', { name: 'Reviewed GPIO', exact: true }).selectOption('18');
  await bench.getByLabel('Commissioning reason', { exact: true }).fill('TLS protocol simulator test');
  await bench.getByLabel('Only an isolated LED is connected').check();
  await bench.getByRole('button', { name: 'Arm LED bench', exact: true }).click();
  await expect(bench.getByText('Hardware bench running', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Signals', exact: true }).click();
  const physicalRow = page.getByRole('row').filter({ hasText: 'TLS LED bench.led' });
  await expect(physicalRow).toContainText('Good');
  await physicalRow.getByRole('button', { name: 'Control', exact: true }).click();
  await page.getByLabel('Command reason', { exact: true }).fill('TLS simulator output');
  await page.getByRole('button', { name: 'Send ON', exact: true }).click();
  await expect(page.getByRole('status', { name: 'Command status' })).toContainText('Verified');
  await page.getByRole('button', { name: 'Devices', exact: true }).click();
  await bench.getByLabel('Commissioning reason', { exact: true }).fill('End TLS simulator test');
  await bench.getByRole('button', { name: 'Disarm LED bench', exact: true }).click();
  await expect(bench.getByText('Hardware bench stopped', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/physical-commissioning.png', fullPage: true });

  await page.getByRole('button', { name: 'Activity', exact: true }).click();
  await expect(page.getByText('Device created', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await page.screenshot({ path: 'test-results/overview-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Switch to light theme' }).click();
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.screenshot({ path: 'test-results/overview-light.png', fullPage: true });
  await page.getByRole('button', { name: 'Sign out' }).click();
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible();
  expect(errors).toEqual([]); expect(external).toEqual([]);
});

test('keeps forms and navigation usable on phone and tablet widths', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 });
  await login(page);
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('button', { name: 'Devices', exact: true }).click();
  await expect(page.getByLabel('Device name', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/devices-phone.png', fullPage: true });
  await page.setViewportSize({ width: 768, height: 1024 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('shows a useful login failure without exposing protected content', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Username', { exact: true }).fill('operator');
  await page.getByLabel('Password', { exact: true }).fill('incorrect password');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Invalid credentials');
  await expect(page.getByRole('button', { name: 'Projects', exact: true })).toHaveCount(0);
});
