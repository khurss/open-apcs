import { signIn } from './auth.js';
import { expect, test } from '@playwright/test';
test.use({actionTimeout: 5000});

test('opens projects by keyboard, preserves context and runs the prepared virtual demo', async ({ page }) => {
  test.setTimeout(90000);
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await signIn(page);
  await page.getByRole('button', {name:'Projects',exact:true}).click();
  await page.getByRole('button', {name:'Open demo project',exact:true}).click();
  await expect(page.getByRole('heading', {name:'Automation demo',exact:true})).toBeVisible();
  await expect(page).toHaveURL(/project=[0-9a-f-]+/);
  const projectUrl = page.url();
  await page.reload();
  await expect(page.getByRole('heading', {name:'Automation demo',exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Devices',exact:true}).click();
  await expect(page.getByRole('article')).toHaveCount(2);
  const thermal = page.getByRole('article').filter({hasText:'Climate chamber'});
  await thermal.getByRole('button', {name:'Start simulator',exact:true}).click();
  await expect(thermal.getByText('Simulation running',{exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Logic',exact:true}).click();
  await page.getByRole('button', {name:'Open Climate PID',exact:true}).click();
  await expect(page.getByText('Prepared revisions',{exact:true})).toBeVisible();
  await page.getByLabel('Activation reason',{exact:true}).fill('Demo acceptance');
  await page.getByRole('button', {name:'Activate revision 1',exact:true}).click();
  await expect(page.getByRole('status',{name:'Graph runtime'})).toContainText('running');
  await page.getByRole('button', {name:'Screens',exact:true}).click();
  await page.getByRole('button', {name:'Open Climate overview',exact:true}).click();
  await page.getByRole('button', {name:'Operate revision 1',exact:true}).click();
  await expect(page.getByRole('region', {name:'Live numeric values'})).toContainText('Good');
  await page.getByRole('button', {name:'Logic',exact:true}).click();
  await page.getByRole('button', {name:'Open Climate PID',exact:true}).click();
  await page.getByLabel('Activation reason',{exact:true}).fill('End demo acceptance');
  await page.getByRole('button', {name:'Stop graph',exact:true}).click();
  await page.getByRole('button', {name:'Devices',exact:true}).click();
  await expect(thermal.getByText('Simulation stopped',{exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Projects',exact:true}).click();
  const link = page.getByRole('link', {name:/Open Automation demo/});
  await link.focus(); await page.keyboard.press('Enter');
  await expect(page).toHaveURL(projectUrl);
  await page.goBack(); await expect(page.getByRole('heading',{name:'Your projects',exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});

test('edits catalog names, filters a project and preserves metadata after reload', async ({page}) => {
  await signIn(page);
  await page.getByRole('button',{name:'Projects',exact:true}).click();
  await page.getByLabel('Project name',{exact:true}).fill('Catalog metadata bench');
  await page.getByRole('button',{name:'Create project',exact:true}).click();
  await page.getByRole('link',{name:'Open Catalog metadata bench',exact:true}).click();
  await page.getByRole('button',{name:'Open devices',exact:true}).click();
  await page.getByLabel('Device name',{exact:true}).fill('Test lamp');
  await page.getByLabel('Site ID',{exact:true}).fill('catalog-browser');
  await page.getByLabel('Device address',{exact:true}).fill('lamp');
  await page.getByRole('button',{name:'Add device',exact:true}).click();
  const card=page.getByRole('article'); await expect(card).toHaveCount(1);
  await card.locator('summary').click();
  await card.getByLabel('New name for Test lamp',{exact:true}).fill('Workshop light');
  await card.getByRole('button',{name:'Save name',exact:true}).click();
  await expect(card.getByRole('heading',{name:'Workshop light',exact:true})).toBeVisible();
  await page.getByLabel('Search devices',{exact:true}).fill('unmatched'); await expect(card).toHaveCount(0);
  await page.getByLabel('Search devices',{exact:true}).fill('Workshop'); await expect(card).toHaveCount(1);
  await page.getByRole('button',{name:'Signals',exact:true}).click();
  const row=page.getByRole('row').filter({hasText:'Test lamp.led'});
  await row.locator('summary').click();
  await row.getByLabel('New name for Test lamp.led',{exact:true}).fill('Workshop output');
  await row.getByRole('button',{name:'Save name',exact:true}).click();
  await expect(page.getByRole('row').filter({hasText:'Workshop output'})).toBeVisible();
  await page.reload(); await expect(page.getByRole('row').filter({hasText:'Workshop output'})).toBeVisible();
  await page.getByRole('button',{name:'Project home',exact:true}).click();
  await page.locator('summary').click();
  await page.getByLabel('New name for Catalog metadata bench',{exact:true}).fill('Workshop project');
  await page.getByRole('button',{name:'Save name',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Workshop project',exact:true})).toBeVisible();
});
