import { expect, test } from '@playwright/test';
test('edits, saves, simulates and prepares a graph, then persists an HMI with undo and redo', async ({ page }) => {
  test.setTimeout(60000);
  await page.goto('/');
  await page.getByLabel('Username', { exact: true }).fill('operator');
  await page.getByLabel('Password', { exact: true }).fill('E2E fixture password only!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'Projects', exact: true }).click();
  await page.getByLabel('Project name', { exact: true }).fill('Editor bench');
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  await expect(page.getByText('Editor bench', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Devices', exact: true }).click();
  await page.getByLabel('Device name', { exact: true }).fill('Editor LED');
  await page.getByLabel('Site ID', { exact: true }).fill('editor');
  await page.getByLabel('Device address', { exact: true }).fill('virtual-1');
  await page.getByRole('button', { name: 'Add device', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Editor LED', exact: true })).toBeVisible();
  await page.getByRole('article').filter({ hasText: 'Editor LED' }).getByRole('button', { name: 'Start simulator', exact: true }).click();
  await expect(page.getByText('Simulation running', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Logic', exact: true }).click();
  await page.getByLabel('Scheme name', { exact: true }).fill('LED automation');
  await page.getByRole('button', { name: 'Create graph', exact: true }).click();
  await page.getByRole('button', { name: 'LED template', exact: true }).click();
  await page.getByRole('button', { name: 'Select Power', exact: true }).click();
  await page.getByLabel('Constant value', { exact: true }).check();
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(page.getByText('Saved revision 2', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Run simulation', exact: true }).click();
  await expect(page.getByRole('status', { name: 'Simulation result' })).toContainText('ON');
  await page.getByRole('button', { name: 'Prepare revision', exact: true }).click();
  await expect(page.getByText('Revision 2 prepared', { exact: true })).toBeVisible();
  await page.getByLabel('Activation reason', { exact: true }).fill('Browser headless LED workflow');
  await page.getByRole('button', { name: 'Activate revision 2', exact: true }).click();
  await expect(page.getByRole('status', { name: 'Graph runtime' })).toContainText('running · r2');
  await page.reload();
  await page.getByRole('button', { name: 'Logic', exact: true }).click();
  await page.getByRole('button', { name: 'Open LED automation', exact: true }).click();
  await expect(page.getByRole('status', { name: 'Graph runtime' })).toContainText('running · r2');
  await page.screenshot({ path: 'test-results/logic-editor.png', fullPage: true });
  await page.getByRole('button', { name: 'Select Power', exact: true }).click();
  await page.getByLabel('Constant value', { exact: true }).uncheck();
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(page.getByText('Saved revision 3', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Compare revision 2', exact: true }).click();
  await expect(page.getByRole('table', { name: 'Revision changes' })).toContainText('/document/nodes/0/value');
  await page.getByLabel('Restore reason', { exact: true }).fill('Restore reviewed ON behavior');
  await page.getByRole('button', { name: 'Restore revision 2 to draft', exact: true }).click();
  await expect(page.getByText('Restored revision 2 as draft 4', { exact: true })).toBeVisible();
  await expect(page.getByRole('status', { name: 'Graph runtime' })).toContainText('running · r2');
  await page.getByRole('button', { name: 'Select Power', exact: true }).click();
  await expect(page.getByLabel('Constant value', { exact: true })).toBeChecked();
  await page.screenshot({ path: 'test-results/revision-restore.png', fullPage: true });

  await page.getByLabel('Activation reason', { exact: true }).fill('End browser graph test');
  await page.getByRole('button', { name: 'Stop graph', exact: true }).click();
  await expect(page.getByRole('status', { name: 'Graph runtime' })).toContainText('stopped');
  await page.getByRole('button', { name: 'Screens', exact: true }).click();
  await page.getByLabel('Scheme name', { exact: true }).fill('LED overview');
  await page.getByRole('button', { name: 'Create screen', exact: true }).click();
  await page.getByRole('button', { name: 'Add indicator', exact: true }).click();
  await page.getByLabel('Element label', { exact: true }).fill('Status lamp');
  await page.getByRole('button', { name: 'Add button', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Select Button', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Select Button', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Select Button', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(page.getByText('Saved revision 2', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Screens', exact: true }).click();
  await page.getByRole('button', { name: 'Open LED overview', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Select Status lamp', exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/hmi-editor.png', fullPage: true });
  await page.getByRole('button', { name: 'Prepare revision', exact: true }).click();
  await page.getByRole('button', { name: 'Operate revision 2', exact: true }).click();
  await expect(page.getByRole('img', { name: /Status lamp:/ })).toContainText('Disconnected');
  await expect(page.getByRole('button', { name: 'Control Button', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Back to editor', exact: true }).click();
  await page.getByRole('button', { name: 'Devices', exact: true }).click();
  await page.getByRole('article').filter({ hasText: 'Editor LED' }).getByRole('button', { name: 'Start simulator', exact: true }).click();
  await expect(page.getByText('Simulation running', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Screens', exact: true }).click();
  await page.getByRole('button', { name: 'Open LED overview', exact: true }).click();
  await page.getByRole('button', { name: 'Operate revision 2', exact: true }).click();
  await expect(page.getByRole('img', { name: /Status lamp:/ })).toContainText('OFF · Good');
  await page.getByRole('button', { name: 'Control Button', exact: true }).click();
  await page.getByLabel('Command reason', { exact: true }).fill('Operator HMI test');
  await page.getByRole('button', { name: 'Send ON', exact: true }).click();
  await expect(page.getByRole('status', { name: 'Command status' })).toContainText('Verified');
  await expect(page.getByRole('img', { name: /Status lamp:/ })).toContainText('ON · Good');
  await page.route('**/api/v1/signals/*/value', (route) => route.abort());
  await expect(page.getByRole('img', { name: /Status lamp:/ })).toContainText('ON · Disconnected');
  await expect(page.getByRole('button', { name: 'Send OFF', exact: true })).toBeDisabled();
  await page.unroute('**/api/v1/signals/*/value');
  await expect(page.getByRole('img', { name: /Status lamp:/ })).toContainText('ON · Good');
  await page.setViewportSize({ width: 360, height: 800 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect.poll(() => page.locator('.sidebar').evaluate((element) => element.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await page.screenshot({ path: 'test-results/hmi-operator-phone.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Send OFF', exact: true }).click();
  await expect(page.getByRole('status', { name: 'Command status' })).toContainText('Verified');
  await expect(page.getByRole('img', { name: /Status lamp:/ })).toContainText('OFF · Good');
});
